(* The error-resilient parser of Jasmin, with Mastic.

   [strict] is the normal path of Jasmin (the parser generated by Menhir,
   the lexer raises on errors); [resilient] never fails: it returns the
   errors, the tokens inserted by the recovery and an AST with error nodes. *)

open Syntax
module I = Parser.MenhirInterpreter

(* the normal path, as Jasmin's Parseio.parse_program *)
let strict lexbuf = Parser.module_ Lexer.main lexbuf

(* the text being parsed, to know where lines begin and to keep the text of
   the tokens folded into an error *)
let text = ref ""

(* the baseline strategy of section 9 of the README (JAZZ_BASELINE set) *)
let baseline = Sys.getenv_opt "JAZZ_BASELINE" <> None

module ProgramParser = struct
  type ast = pprogram
  type 'a checkpoint = 'a I.checkpoint
  let main = Parser.Incremental.module_
  type token = Parser.token
  let token = Lexer.main
end

