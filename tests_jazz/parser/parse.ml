  let pp_symbol : type a. a option -> Format.formatter -> a symbol -> unit =
    fun _ fmt s -> Format.pp_print_string fmt (name_of_symbol s)

  (* INSTR_ERROR_TOKEN is an error that only an instruction (or an item)
     accepts, ITEM_ERROR_TOKEN one that only an item accepts: Mastic folds
     the stack into it up to the instruction, or the item, which becomes an
     error. When Mastic merges errors it rebuilds the token from the merged
     Mastic.Error.t, so they are marked by a piece Lex "\001" or Lex "\000",
     which survives the merges. *)
  let item_marker = "\000"  (* not used *)
  let instr_marker = "\001"
  let has_marker m e = List.exists (fun x -> Mastic.Error.unloc x = Mastic.Error.Lex m) e
  let match_error_token = function
    | Parser.ERROR_TOKEN x | Parser.INSTR_ERROR_TOKEN x | Parser.ITEM_ERROR_TOKEN x -> Some x
    | _ -> None
  let build_error_token t =
    if has_marker item_marker t then Parser.ITEM_ERROR_TOKEN t
    else if has_marker instr_marker t then Parser.INSTR_ERROR_TOKEN t
    else Parser.ERROR_TOKEN t
  let is_eof_token = function Parser.EOF -> true | _ -> false

  (* the tokens the recovery may insert: the end of an instruction, and
     closing brackets *)
  let token_of_terminal : type a. a terminal -> (string * token) option =
    fun t -> if baseline then None else match t with
    | I.T_SEMICOLON -> Some (";", Parser.SEMICOLON)
    | I.T_RPAREN -> Some (")", Parser.RPAREN)
    | I.T_RBRACKET -> Some ("]", Parser.RBRACKET)
    | I.T_RBRACE -> Some ("}", Parser.RBRACE)
    | I.T_LBRACE -> Some ("{", Parser.LBRACE)
    | _ -> None

  (* -------------------------------------------------------------------- *)
  (* An item of the stack folded into an error keeps its content:
     expressions, types, left values, instructions and items become the
     error nodes of their type, the elements of lists are kept one by one,
     and anything else is kept as text *)

  let slice (b : Lexing.position) (e : Lexing.position) =
    let b = max 0 b.pos_cnum and e = min (String.length !text) e.pos_cnum in
    if e <= b then "" else String.sub !text b (e - b)
  let txt b e = Mastic.Error.(mkLexError (loc (slice b e) b e))

  let pos_of_loc (l : Location.t) =
    let p (line, col) n = { Lexing.pos_fname = l.loc_fname; pos_lnum = line; pos_bol = n - col; pos_cnum = n } in
    p l.loc_start l.loc_bchar, p l.loc_end l.loc_echar
  let located build x (l : Location.t) = let b, e = pos_of_loc l in build (Mastic.Error.loc x b e)
  let expr (x : pexpr) = located Expr.build_token x x.pl_loc
  let typ (x : ptype) = located Type.build_token x x.pl_loc
  let lvalue (x : plvalue) = located Lvalue.build_token x x.pl_loc
  let instr ((_, i) as x : pinstr) = located Instr.build_token x i.pl_loc
  let item (x : pitem Location.located) = located Item.build_token x.pl_desc x.pl_loc
  let all f l b e = match List.map f l with [] -> txt b e | x :: xs -> List.fold_left Mastic.Error.merge x xs
  (* the text, with the pieces of [l] inside it *)
  let with_text l b e = List.fold_left Mastic.Error.merge (txt b e) l

  let reduce_as_parse_error : type a. a -> a symbol -> Lexing.position -> Lexing.position -> token =
    fun x s b e ->
    let here build = build (Mastic.Error.loc x b e) in
    let wrap build v = build (Mastic.Error.loc (Location.mk_loc (Location.make b e) v) b e) in
    Parser.ERROR_TOKEN (match s with
    | I.N I.N_pexpr -> here Expr.build_token
    | I.N I.N_pexpr_noarr -> here Expr.build_token
    | I.N I.N_arr_access_len -> here Expr.build_token
    | I.N I.N_pexpr_r -> wrap Expr.build_token x
    | I.N I.N_pexpr_noarr_r_pexpr_ -> wrap Expr.build_token x
    | I.N I.N_pexpr_noarr_r_pexpr_noarr_ -> wrap Expr.build_token x
    | I.N I.N_option_prefix_IF_pexpr__ -> with_text (Option.to_list (Option.map expr x)) b e
    | I.N I.N_option_arr_access_len_ -> with_text (Option.to_list (Option.map expr x)) b e
    | I.N I.N_separated_nonempty_list_COMMA_pexpr_ -> all expr x b e
    | I.N I.N_separated_nonempty_list_COMMA_pexpr_noarr_ -> all expr x b e
    | I.N I.N_loption_separated_nonempty_list_COMMA_pexpr__ -> all expr x b e
    | I.N I.N_loption_separated_nonempty_list_COMMA_pexpr_noarr__ -> all expr x b e
    | I.N I.N_pgexpr -> (match x with GEexpr x -> expr x | GEarray l -> with_text (List.map expr l) b e)
    | I.N I.N_ptype -> here Type.build_token
    | I.N I.N_ptype_r -> wrap Type.build_token x
    | I.N I.N_stor_type -> with_text [typ (snd x)] b e
    | I.N I.N_annot_stor_type -> with_text [typ (snd (snd x))] b e
    | I.N I.N_plvalue -> here Lvalue.build_token
    | I.N I.N_plvalue_r -> wrap Lvalue.build_token x
    | I.N I.N_separated_nonempty_list_COMMA_plvalue_ -> all lvalue x b e
    | I.N I.N_plvalues -> with_text (List.map lvalue (snd x)) b e
    | I.N I.N_pinstr -> here Instr.build_token
    | I.N I.N_pinstr_r -> Instr.build_token (Mastic.Error.loc ([], Location.mk_loc (Location.make b e) x) b e)
    | I.N I.N_pif -> Instr.build_token (Mastic.Error.loc ([], Location.mk_loc (Location.make b e) x) b e)
    | I.N I.N_list_pinstr_ -> all instr x b e
    | I.N I.N_pblock_r -> all instr x b e
    | I.N I.N_pblock -> all instr x.pl_desc b e
    | I.N I.N_pelse -> all instr x.pl_desc b e
    | I.N I.N_option_pblock_ -> (match x with Some x -> all instr x.pl_desc b e | None -> txt b e)
    | I.N I.N_pfunbody -> with_text (List.map instr x.pdb_instr) b e
    | I.N I.N_top -> here Item.build_token
    | I.N I.N_list_loc_top__ -> all item x b e
    | _ -> txt b e)

  (* -------------------------------------------------------------------- *)
  (* the state of the parser *)

  let lhs_is f (lhs, _, _, _) = match lhs with I.X (I.N n) -> f (I.X (I.N n)) | _ -> false

  (* an item of an expression *)
  let is_expr = lhs_is (function
    | I.X (I.N (I.N_pexpr | I.N_pexpr_r | I.N_pexpr_noarr | I.N_pexpr_noarr_r_pexpr_
               | I.N_pexpr_noarr_r_pexpr_noarr_)) -> true
    | _ -> false)

  (* the state waits for an expression, a type or a left value: an item
     expects one next, and no item is complete *)
  (* the next symbol of an item, after the ones that can be empty (castop
     in x + y) *)
  let next (_, rhs, _, pos) =
    let rec skip = function
      | I.X (I.N n) :: rest when I.nullable n && rest <> [] -> skip rest
      | l -> l in
    List.nth_opt (skip (List.filteri (fun i _ -> i >= pos) rhs)) 0

  let expects_expr_or_type productions =
    List.for_all (fun i -> next i <> None) productions &&
    List.exists (fun i -> match next i with
      | Some (I.X (I.N (I.N_pexpr | I.N_pexpr_noarr | I.N_ptype | I.N_plvalue))) -> true
      | _ -> false) productions

  (* the beginning of an item: at the beginning of the file (the kernel item
     of the initial state), after an item, or after "namespace N {" *)
  let is_item_start (lhs, rhs, _, pos) =
    match lhs, pos with
    | I.X (I.N I.N_list_loc_top__), 1 -> true
    | I.X (I.N I.N_module_), 0 -> true
    | I.X (I.N I.N_top), 3 -> (match rhs with I.X (I.T I.T_NAMESPACE) :: _ -> true | _ -> false)
    | _ -> false

  (* the state waits for a block, or the body of a function *)
  let expects_block productions =
    List.exists (fun i -> match next i with
      | Some (I.X (I.N (I.N_pblock | I.N_pblock_r | I.N_pfunbody))) -> true
      | _ -> false) productions

  (* between two instructions of a block *)
  let is_instr_start (lhs, rhs, _, pos) =
    match lhs, pos with
    | I.X (I.N I.N_list_pinstr_), 1 -> true
    | I.X (I.N (I.N_pblock_r | I.N_pfunbody)), 1 -> true
    | _ -> false

  (* -------------------------------------------------------------------- *)
  (* restart points *)

  (* the token is the first of its line *)
  let first_on_line (p : Lexing.position) =
    let rec blank i = i >= p.pos_cnum || ((!text).[i] = ' ' || (!text).[i] = '\t') && blank (i + 1) in
    p.pos_cnum <= String.length !text && blank p.pos_bol

  (* the token probably begins the next item: a keyword that only begins
     items, or a token at the beginning of a line (column 0) *)
  let item_restart t (p : Lexing.position) =
    match t with
    | Parser.FN | Parser.PARAM | Parser.EXPORT | Parser.REQUIRE | Parser.FROM
    | Parser.NAMESPACE | Parser.EXEC | Parser.TYPE -> true
    | Parser.RBRACE | Parser.LBRACE -> false
    | _ -> p.pos_cnum = p.pos_bol

  (* the token probably begins the next instruction: a keyword that only
     begins instructions, or the first token of a line *)
  let instr_restart t (p : Lexing.position) =
    match t with
    | Parser.IF | Parser.FOR | Parser.WHILE | Parser.ARRAYINIT | Parser.ASSERT | Parser.RETURN -> true
    | Parser.RBRACE | Parser.LBRACE | Parser.ELSE -> false
    | _ -> first_on_line p

  (* -------------------------------------------------------------------- *)

  let handle_unexpected_token ~productions ~next_token ~acceptable_tokens
      ~reducible_productions ~generation_streak =
    let open Mastic.ErrorResilientParser in
    let accept l = List.find_map (fun t -> List.find_opt (fun x -> x.t = t) acceptable_tokens) l in
    let marked m t s =
      let b = next_token.b in
      GenerateToken { s; b; e = b; t = t Mastic.Error.(mkLexError (loc m b b)) } in
    let lbrace () = GenerateToken { s = "{"; t = Parser.LBRACE; b = next_token.b; e = next_token.b } in
    let instr_error () = marked instr_marker (fun x -> Parser.INSTR_ERROR_TOKEN x) "(error)" in
    (* between two instructions of a block, or two items of a namespace *)
    let in_block = List.exists (fun i -> is_instr_start i || is_item_start i) productions in
    (* finish the current item (at the end of the file, or at a token that
       begins an item): reduce if possible, otherwise insert the ";" or a
       bracket if it fits, between two instructions close the block, then
       try a hole for a missing expression, and finally make the current
       instruction an error (or the item, outside a function) *)
    let finish_item () =
      match reducible_productions with
      | p :: _ -> Reduce p
      | [] ->
      match accept Parser.[SEMICOLON; RPAREN; RBRACKET; RBRACE; LBRACE] with
      | Some x -> GenerateToken x
      | None ->
          if expects_block productions then lbrace ()
          else if in_block then GenerateToken { s = "}"; t = Parser.RBRACE; b = next_token.b; e = next_token.b }
          else if generation_streak <= 1 then GenerateHole
          else instr_error () in
    (* finish the current instruction (at a token that begins an
       instruction): the same, without closing the block, and inserting
       the ";" anyway (Menhir may accept it after reductions of empty rules,
       that Mastic does not list) *)
    let finish_instr () =
      match reducible_productions with
      | p :: _ -> Reduce p
      | [] ->
      match accept Parser.[SEMICOLON; RPAREN; RBRACKET] with
      | Some x -> GenerateToken x
      | None ->
          if expects_block productions then lbrace ()
          else if next_token.t <> Parser.SEMICOLON && generation_streak <= 1 then
            GenerateToken { s = ";"; t = Parser.SEMICOLON; b = next_token.b; e = next_token.b }
          else if generation_streak <= 2 then GenerateHole
          else instr_error () in
    if baseline then
      match reducible_productions with
      | p :: _ when List.exists is_expr productions -> Reduce p
      | _ -> TurnIntoError
    else
    if generation_streak >= 10 then TurnIntoError
    else if List.exists is_item_start productions && next_token.t <> Parser.EOF then TurnIntoError
    else if reducible_productions = [] && generation_streak = 0 && expects_expr_or_type productions then
      (* an expression (or a type, a left value) is missing: an error node
         takes its place, as in x = a + ; read x = a + Err; *)
      GenerateHole
    else match next_token.t with
    | Parser.EOF -> finish_item ()
    | t when item_restart t next_token.b -> finish_item ()
    | t when instr_restart t next_token.b -> finish_instr ()
    | Parser.RBRACE -> finish_instr ()
    | Parser.LBRACE when generation_streak = 0 ->
        (* a block that does not fit: what is before it is broken, a hole
           folds it into an error, after which the block may fit (as the
           body of a function whose header is broken, for instance) *)
        GenerateHole
    | _ ->
    match reducible_productions with
    | p :: _ when List.exists is_expr productions -> Reduce p
    | _ -> TurnIntoError
end

module ErProgram = Mastic.ErrorResilientParser.Make (I) (ProgramParser) (Recovery)

let () = Mastic.ErrorResilientParser.debug := Sys.getenv_opt "MASTIC_DEBUG" <> None

(* consecutive error items, and consecutive error instructions, are merged *)
let rec merge_items = function
  | { Location.pl_desc = PError x; pl_loc = l } :: { Location.pl_desc = PError y; pl_loc = l' } :: rest ->
      merge_items ({ Location.pl_desc = PError (Mastic.Error.merge x y); pl_loc = Location.merge l l' } :: rest)
  | ({ Location.pl_desc = PFundef f; _ } as d) :: rest ->
      { d with pl_desc = PFundef { f with pdf_body = { f.pdf_body with pdb_instr = merge_instrs f.pdf_body.pdb_instr } } }
      :: merge_items rest
  | ({ Location.pl_desc = PFunError (e, b); _ } as d) :: rest ->
      { d with pl_desc = PFunError (e, { b with pdb_instr = merge_instrs b.pdb_instr }) } :: merge_items rest
  | ({ Location.pl_desc = PNamespace (n, l); _ } as d) :: rest ->
      { d with pl_desc = PNamespace (n, merge_items l) } :: merge_items rest
  | d :: rest -> d :: merge_items rest
  | [] -> []

and merge_instrs = function
  | (a, ({ Location.pl_desc = PIError x; _ } as i)) :: (_, { Location.pl_desc = PIError y; pl_loc = l' }) :: rest ->
      merge_instrs ((a, { Location.pl_desc = PIError (Mastic.Error.merge x y); pl_loc = Location.merge i.pl_loc l' }) :: rest)
  | (a, i) :: rest -> (a, { i with pl_desc = merge_instr i.pl_desc }) :: merge_instrs rest
  | [] -> []

and merge_block (b : pblock) = { b with pl_desc = merge_instrs b.pl_desc }

and merge_instr = function
  | PIIf (c, b1, b2) -> PIIf (c, merge_block b1, Option.map merge_block b2)
  | PIFor (v, r, b) -> PIFor (v, r, merge_block b)
  | PIWhile (b1, c, b2) -> PIWhile (Option.map merge_block b1, c, Option.map merge_block b2)
  | PIErrorBlock (e, b) -> PIErrorBlock (e, merge_block b)
  | i -> i

(* One resilient parse: the lexer returns error tokens instead of raising;
   its errors are added to the ones of Mastic, one per position. *)
let resilient lexbuf =
  text := Bytes.sub_string lexbuf.Lexing.lex_buffer 0 lexbuf.Lexing.lex_buffer_len;
  let saved = !Lexer.recovering, !Lexer.errors in
  Lexer.recovering := not baseline; Lexer.errors := [];
  let errs, comps, ast = Fun.protect ~finally:(fun () -> Lexer.recovering := fst saved; Lexer.errors := snd saved)
    (fun () ->
      let errs, comps, ast = ErProgram.parse lexbuf in
      let lex = List.map (fun (p, m) -> Mastic.ErrorResilientParser.LexError (p, m)) !Lexer.errors in
      lex @ errs, comps, ast) in
  (* the errors, in the order of the text *)
  let pos = function Mastic.ErrorResilientParser.LexError (p, _) | ParseError (p, _) -> p.Lexing.pos_cnum in
  let errs = List.stable_sort (fun x y -> compare (pos y) (pos x)) errs in
  let rec dedup = function
    | x :: (y :: _ as rest) when pos x = pos y -> dedup (x :: List.tl rest)
    | x :: rest -> x :: dedup rest
    | [] -> [] in
  dedup (List.rev errs), comps, merge_items ast
